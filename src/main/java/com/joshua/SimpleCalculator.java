
public class SimpleCalculator {
    public static void main(String[] args) {
        int firstNumber = 20;
        int secondNumber = 6;
        System.out.println(firstNumber + secondNumber);

        System.out.println(firstNumber - secondNumber);

        System.out.println(firstNumber * secondNumber);

        System.out.println(firstNumber / secondNumber);

        System.out.println(firstNumber % secondNumber);
    }
}